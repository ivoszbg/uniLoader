/*
 * SD-card XNU boot path (Samsung J1 / Exynos 3475, SM-J120F).
 *
 * Loads plain (uncompressed) boot blobs off the FAT32 SD card straight
 * into their final physical addresses, then jumps into XNU - the same
 * layout the embedded .payload path in load-kernel.c would produce, but
 * with no LZ4/gzip/RDSC decode step (space is plentiful, so the files on
 * the card are kept raw).
 *
 * Files expected on the card root:
 *   Image     - flat kernel image (xnu.raw, xnu entry covered)
 *   dtb       - Apple-format flattened device tree
 *   ramdisk   - raw HFS+ root filesystem image (no RDSC / gzip wrap)
 *   cacheslice- the FULL uncompressed dyld_shared_cache_armv7; read to a
 *              reserved area above the ramdisk and passed to the kernel
 *              as a single dsc=pa,0,size triple
 *
 * Memory layout (mirrors arch_load_kernel_xnu):
 *   load_pa        Image
 *   load_pa+ksize  + 16MB guard       dtb
 *   dt_pa+dtsize   aligned            boot_args
 *   ba_pa+sizeof   aligned            ramdisk
 *
 * Returns 0 when it jumped into XNU (never returns), -1 on any error so
 * the caller can fall back to the embedded payload.
 */

