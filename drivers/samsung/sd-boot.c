/*
 * BRING-UP (J1, Sep 29) - HARDWARE VALUES FOR THE SD BOOT PATH.
 *
 * The CONFIG_XNU_* macros above all come from include/generated/autoconf.h,
 * which is REGENERATED by whichever `make <board>_defconfig` ran last.  A
 * QEMU build overwrites it with the qemu -M virt layout (PHYS_BASE
 * 0x40800000, MEMSIZE 0x3F800000, FB_BASE 0x50000000) and, because
 * autoconf.h always defines them, the `#ifndef` fallbacks above are DEAD
 * CODE.  The J1 SD path then hands XNU a physical window shifted by
 * 0x10800000 (~276 MB) and points Video.v_baseAddr at 0x50000000, which
 * is the QEMU placeholder - NOT the real J1 panel at 0x57E05000.  That
 * silently breaks the free-page model (commpage L1 allocation can never
 * find 4 aligned free pages) and the screen.
 *
 * This driver is the real Exynos SD-MMC path and is only ever used for the
 * phone, so the values are pinned here and cannot be leaked in from a QEMU
 * config run.  Keep them in sync with configs/j1xlte_defconfig.
 */
#define J1_SD_PHYS_BASE		0x30000000
#define J1_SD_MEMSIZE		0x25E00000
#define J1_SD_FB_BASE		0x57E05000
#define J1_SD_FB_WIDTH		480
#define J1_SD_FB_HEIGHT		800
#define J1_SD_CMDLINE		"-v keepsyms=1 kprintf=1 debug=0x14e j1slot=0x2fe26624 j1uart=1 init=/sbin/launchd"
/* mji: default = launchd (init= is per-test TEMP, set only for direct/shim
 * runs and reverted after). j1uart=1 is emulator-only. */
/* mji Oct 8 2026: default = launchd (phone + emulator). init=/j1boot and
 * init=/j1sb are per-test TEMP additions, never committed here. */

/*
 * BRING-UP (mji): the kernel builds its dyld shared-cache serve table ONLY
 * from the `dsc=` bootarg (shared_region_check_np -> shared_region_map_np
 * populates j1_dsc_*, which gates the j1seg table in bsd_vm.c).  The B1
 * plan - cache as an ordinary file on the block rootfs through the stock
 * pager - is NOT wired into the kernel yet, so with staging off the kernel
 * returns EINVAL (no dsc), the serve table stays empty and dyld cannot
 * find any cached image.  Stage the full cacheslice into RAM above the
 * ramdisk and append dsc=<pa>,0,<size>.  Define to 0 (or comment out) to
 * fall back to the `#else` B1 branch below.
 */
/* mji TEST 2026-10-12: disabled to test ios7 B1 path (staging OFF) */
#define J1_STAGE_CACHESLICE 1

/*
 * Boot progress bar painted straight into the panel, bypassing printk.
 *
 * simplefb draws its text from y = FB_TEXT_TOP_PADDING (5) downwards, so
 * pixel rows 0..4 are never touched by text.  Each boot step repaints the
 * whole bar (not just one more pixel) into row 2, because clean_fbmem()
 * wipes the entire framebuffer on overflow and a partial bar would be
 * destroyed by the hundreds of clears during the 154 MB cacheslice read.
 * The last repaint therefore always shows the LAST milestone reached, and
 * it survives every screen clear that happened before it.
 *
 * Thin wrapper around simplefb_mark(), which lives in simplefb.c because it
 * needs fb_info->address - the panel address is not otherwise reachable
 * from here.  See the comment on simplefb_mark() for the block layout.
 */
static void j1_fb_mark(unsigned int step)
{
	simplefb_mark(step);
}

/*
 * Progress marker: pixel blocks on the framebuffer PLUS a readable line.
 * The blocks alone cannot be counted reliably in a phone photo, and the
 * readable line is the decisive channel because printk() is known to work
 * for the ~20 lines printed before this point.  The LAST line on screen is
 * the last stage that actually completed.
 */
static void j1_fb_stage(unsigned int step)
{
	simplefb_mark(step);
	printk(KERN_INFO, "J1S%u\n", step);
}

/*
 * Append a short literal.  NOT memcpy: this toolchain's __memcpy_arm copies
 * only 4 of 6 bytes for len==6 (it jumps into the middle of its unrolled
 * ladder at 0x2000a650, copies the single 4-byte step, then the tail path
 * is gated on `len << 31` which is 0 for len 6 - so two bytes are left
 * stale).  A byte loop is correct for every length.
 */
static void j1_puts(char *p, const char *s, unsigned int n)
{
	unsigned int i;

	for (i = 0; i < n; i++)
		p[i] = s[i];
}

/* Mirrors pexpert/pexpert/arm/boot.h of the darwin-on-arm XNU tree. */
#define XNU_BOOT_LINE_LENGTH	2048

struct xnu_boot_video {
	uint32_t v_baseAddr;
	uint32_t v_display;
	uint32_t v_rowBytes;
	uint32_t v_width;
	uint32_t v_height;
	uint32_t v_depth;
};

struct xnu_boot_args {
	uint16_t Revision;
	uint16_t Version;
	uint32_t virtBase;
	uint32_t physBase;
	uint32_t memSize;
	uint32_t topOfKernelData;
	struct xnu_boot_video Video;
	uint32_t machineType;
	void *deviceTreeP;	/* virtual address */
	uint32_t deviceTreeLength;
	char CommandLine[XNU_BOOT_LINE_LENGTH];
	uint32_t RamdiskPA;	/* physical address of ramdisk image */
	uint32_t RamdiskSize;	/* size in bytes */
};

static unsigned int align_up(unsigned int v, unsigned int a)
{
	return (v + a - 1) & ~(a - 1);
}

/* Append exactly 8 hex digits of v to p (no NUL, no separators). */
/* Append a 32-bit value as "0x" + 8 hex digits.  The 0x prefix is REQUIRED:
 * PE_parse_boot_argn()/getval() in pexpert/gen/bootargs.c only recognises a
 * hex value after '0x', and a bare "3a3c0000" is classified as a STRING, so
 * the whole j1sd/j1log argument would silently fail to parse in XNU. */
static void sd_append_hex(char *p, unsigned int v)
{
	static const char hexd[] = "0123456789abcdef";
	unsigned int w;

	p[0] = '0';
	p[1] = 'x';
	for (w = 0; w < 8; w++)
		p[2 + w] = hexd[(v >> ((7 - w) * 4)) & 0xf];
}

#define J1SD_HEX_LEN	10		/* "0x" + 8 digits + NUL */

/* Loads one whole file or fails.  @dst must have room for @cap bytes. */
static int sd_load_file(const char *name, void *dst, unsigned int cap,
			unsigned int *out_size)
{
	int n = sd_fat_read(name, dst, cap);

	if (n < 0) {
		printk(KERN_INFO, "xnu: sd %s not-found\n", name);
		return -1;
	}
	*out_size = (unsigned int)n;
	printk(KERN_INFO, "xnu: sd %s %u bytes -> %08x\n",
	       name, *out_size, (unsigned int)dst);
	return 0;
}

/*
 * Read the entry offset straight from the Image's own Mach-O header.
 * sd-xnu.raw begins with the MH_MAGIC header (mkraw.py lays the segments
 * out linearly starting at the lowest __TEXT vmaddr), so uniLoader does
 * not need to be re-flashed every time a kernel edit relinks the entry to
 * a different place.  Falls back to CONFIG_XNU_ENTRY_OFFSET on any parse
 * problem so a non-Mach-O blob still boots with the baked-in guess.
 */
#define J1_MH_MAGIC		0xfeedface
#define J1_LC_SEGMENT		0x1
#define J1_LC_UNIXTHREAD	0x5
#define J1_ARM_THREAD_STATE	1

static unsigned int sd_xnu_entry_offset(unsigned int load_pa,
					unsigned int def)
{
	unsigned char *p = (unsigned char *)load_pa;
	unsigned int base = 0, entry = 0, off;
	unsigned int magic, ncmds;
	int i;

	magic = p[0] | (p[1] << 8) | (p[2] << 16) | ((unsigned)p[3] << 24);
	if (magic != J1_MH_MAGIC)
		return def;
	ncmds = p[16] | (p[17] << 8) | (p[18] << 16) | ((unsigned)p[19] << 24);
	off = 28;
	for (i = 0; i < ncmds; i++) {
		unsigned int cmd, csize = 0;
		cmd = p[off] | (p[off + 1] << 8) | (p[off + 2] << 16) |
		      ((unsigned)p[off + 3] << 24);
		csize = p[off + 4] | (p[off + 5] << 8) | (p[off + 6] << 16) |
			((unsigned)p[off + 7] << 24);
		if (cmd == J1_LC_SEGMENT) {
			unsigned int vmaddr;
			vmaddr = p[off + 24] | (p[off + 25] << 8) |
				 (p[off + 26] << 16) | ((unsigned)p[off + 27] << 24);
			if (base == 0 || vmaddr < base)
				base = vmaddr;
		} else if (cmd == J1_LC_UNIXTHREAD) {
			unsigned int flavor;
			flavor = p[off + 8] | (p[off + 9] << 8) |
				 (p[off + 10] << 16) | ((unsigned)p[off + 11] << 24);
			if (flavor == J1_ARM_THREAD_STATE) {
				/* state[15] = pc, right after flavor+count */
				entry = p[off + 76] | (p[off + 77] << 8) |
					(p[off + 78] << 16) | ((unsigned)p[off + 79] << 24);
			}
		}
		if (csize == 0)
			break;
		off += csize;
	}
	if (base && entry > base)
		return entry - base;
	return def;
}

int sd_arch_load_kernel_xnu(unsigned int phys_base,
			    unsigned int virt_base,
			    unsigned int load_pa)
{
	unsigned int ksize, dtsize, dt_pa, ba_pa, top, rd_pa, rd_size;

	/* Keep the panel readable: hundreds of per-chunk "pio18 ok" lines
	 * would clear the whole screen over and over during the cacheslice
	 * read.  Errors are still printed. */
	sd_chatter = 0;

	/* Unmistakable build tag, printed FIRST.  If this line is absent the
	 * card/phone is running a different boot.img than the one built, and
	 * no later diagnosis on this screen means anything. */
	printk(KERN_INFO, "xnu: J1SD2 tag load_pa=%x\n", load_pa);
	j1_fb_stage(1);
	unsigned int entry_off;
	struct xnu_boot_args *ba;
	void *RamdiskPA;

	if (!sd_is_ready() || sd_fat_mount())
		return -1;

	if (sd_load_file("Image", (void *)load_pa, 0x4000000, &ksize))
		return -1;
	j1_fb_stage(2);

	/* Apple-format device tree right behind the kernel, with the same
	 * BSS guard arch_load_kernel_xnu uses. */
	dt_pa = align_up(load_pa + ksize + 0x1000000, 4);
	if (sd_load_file("dtb", (void *)dt_pa, 0x100000, &dtsize))
		return -1;
	j1_fb_stage(3);

	/* boot_args behind the device tree. */
	ba_pa = align_up(dt_pa + dtsize, 4);
	ba = (struct xnu_boot_args *)ba_pa;
	memset(ba, 0, sizeof(*ba));
	memcpy(ba->CommandLine, J1_SD_CMDLINE,
	       sizeof(J1_SD_CMDLINE) - 1);
	ba->CommandLine[sizeof(J1_SD_CMDLINE) - 1] = 0;

	/* SD kernel log: hand XNU the card identity plus a raw LBA range to
	 * push log sectors at with CMD24.  XNU never touches the FAT, the
	 * directory entry or anything the loader reads.
	 *
	 * The range is ALWAYS the last 8 MiB of the card, never the first
	 * cluster of J1LOG.BIN: that file is fragmented (verified with
	 * build/j1log.py), so writing from its first cluster would destroy
	 * whatever else lives in the fragments. */
#ifdef CONFIG_J1UART_MIRROR
/* Emulator-only (j1qemu_defconfig): ask the kernel to mirror its
 * console to UART2.  Phone defconfig leaves this off. */
	{
		char *q = ba->CommandLine;

		while (*q)
			q++;
		{
			static const char j1u[] = " j1uart=1";

			unsigned int k;

			for (k = 0; k < sizeof(j1u) - 1; k++)
				*q++ = j1u[k];
			*q = 0;
		}
	}
#endif
	{
		uint32_t llba = 0, lns = 0, card, rca;

		rca = sd_get_rca();
		card = (uint32_t)sd_get_sectors();
		if (rca > 0 && card > 16384 + 2048) {
			/* 8 MiB = 16384 sectors, 1 MiB clear of the very last
			 * sector - some cards reserve tail sectors for
			 * internal bookkeeping. */
			llba = (uint32_t)(card - 16384 - 2048);
			lns = 16384;
			printk(KERN_INFO,
			       "xnu: sdlog tail lba=%u nsect=%u card=%u rca=%x\n",
			       llba, lns, card, (unsigned)rca);
			j1_fb_stage(4);
		} else {
			printk(KERN_INFO,
			       "xnu: sdlog off (rca=%x card=%u)\n",
			       (unsigned)rca, card);
			llba = 0;
			lns = 0;
		}
		if (llba && lns) {
			char *p = ba->CommandLine;
			unsigned room = sizeof(ba->CommandLine) - 1;

			while (*p && room)
				p++, room--;

			/* room must cover " j1sd=.. j1sdn=.. j1log=..
			 * j1logn=.." = 4 * (1 + 5 + 2 + J1SD_HEX_LEN) */
			if (room < 4 * (1 + 5 + 2 + J1SD_HEX_LEN)) {
				printk(KERN_INFO,
				       "xnu: sdlog off (cmdline full)\n");
				llba = 0;
				lns = 0;
			} else {
				j1_fb_stage(5);	/* entering the append block */
				j1_puts(p, " j1sd=", 6);
				p += 6;
				sd_append_hex(p, (unsigned)rca);
				p += J1SD_HEX_LEN;
				j1_puts(p, " j1sdn=", 7);
				p += 7;
				sd_append_hex(p, card);
				p += J1SD_HEX_LEN;
				j1_puts(p, " j1log=", 7);
				p += 7;
				sd_append_hex(p, llba);
				p += J1SD_HEX_LEN;
				j1_puts(p, " j1logn=", 8);
				p += 8;
				sd_append_hex(p, lns);
				p += J1SD_HEX_LEN;
				*p = 0;
				j1_fb_stage(6);	/* append done */
				printk(KERN_INFO,
				       "xnu: sdlog args ok cmdline=%u\n",
				       (unsigned)(p - ba->CommandLine));
				j1_fb_stage(7);
				/* Print what we actually built: this verifies the
				 * 0x prefixes and the per-argument lengths in one
				 * shot, which is otherwise invisible. */
				printk(KERN_INFO, "xnu: cmd=[%s]\n",
				       ba->CommandLine);
				j1_fb_stage(8);
			}
		}
	}

	/* Raw HFS+ root image, glued below the boot args (same spot the
	 * embedded path uses for the uncompressed ramdisk fallback). */
	rd_pa = align_up(ba_pa + sizeof(*ba), 4);
	RamdiskPA = (void *)rd_pa;
	printk(KERN_INFO, "xnu: STAGE ramdisk -> %x\n", rd_pa);
	sd_progress_enable(1);
	if (sd_load_file("ramdisk", RamdiskPA, 0x8000000, &rd_size)) {
		sd_progress_enable(0);
		printk(KERN_INFO, "xnu: ramdisk LOAD FAILED\n");
		return -1;
	}
	sd_progress_enable(0);
	printk(KERN_INFO, "xnu: ramdisk %u bytes at %x\n", rd_size, rd_pa);
	j1_fb_stage(9);

#ifdef J1_STAGE_CACHESLICE
	/* BRING-UP (J1): the FULL dyld shared cache, uncompressed, straight
	 * off the card.  It maps linearly at VA base 0x30000000 (fileoff =
	 * VA - 0x30000000 in bsd_vm.c), so ONE (pa,0,len) triple covers the
	 * whole cache: the kernel serves every faulting shared-cache page
	 * from this buffer.  Park it right after the ramdisk and pull
	 * topOfKernelData above it so the VM allocator never hands these
	 * physical pages out. */
	{
		unsigned int cache_pa = align_up(rd_pa + rd_size, 1 << 20);
		unsigned int cache_size = 0;
		unsigned int cap = 0x20000000;	/* 512MB room on the card */

		/* This is a 154 MB read (~301k sectors) with nothing else to
		 * show for it, so bracket it: a silent stop here is the only
		 * way this stage can look like a hang. */
		printk(KERN_INFO, "xnu: STAGE cacheslice -> %x\n", cache_pa);
		sd_progress_enable(1);
		if (sd_load_file("cacheslice", (void *)cache_pa, cap,
				 &cache_size)) {
			sd_progress_enable(0);
			printk(KERN_INFO, "xnu: cacheslice LOAD FAILED\n");
			return -1;
		}
		sd_progress_enable(0);
		printk(KERN_INFO, "xnu: cacheslice %u bytes at %x\n",
		       cache_size, cache_pa);
		j1_fb_stage(10);
		/* Sanity: the shared cache must at least carry the dyld
		 * image that bsd_vm feeds from fileoff 0. */
		if (cache_size < 0x400000) {
			printk(KERN_INFO, "xnu: sd cache too small (%u)\n",
			       cache_size);
			return -1;
		}
		top = align_up(cache_pa + cache_size, 1 << 20);

		/* dsc=pa,0,size  (hex, no 0x - matches PE_parse_boot_argn). */
		{
			static const char hexd[] = "0123456789abcdef";
			unsigned int vals[3] = { cache_pa, 0, cache_size };
			unsigned int q = 0, w, i;

			while (ba->CommandLine[q])
				q++;
			if (q + 1 + 4 + 24 + 1 < sizeof(ba->CommandLine)) {
				ba->CommandLine[q++] = ' ';
				ba->CommandLine[q++] = 'd';
				ba->CommandLine[q++] = 's';
				ba->CommandLine[q++] = 'c';
				ba->CommandLine[q++] = '=';
				for (w = 0; w < 3; w++) {
					unsigned int vv = vals[w];
					int started = 0;

					if (w) {
						ba->CommandLine[q++] = ',';
					}
					for (i = 0; i < 8; i++) {
						int nb = 7 - i;
						unsigned int nib =
						    (vv >> (nb * 4)) & 0xf;

						if (nib || started || nb == 0)
							started = 1;
						if (started) {
							ba->CommandLine[q++] =
							    hexd[nib];
						}
					}
				}
				ba->CommandLine[q] = 0;
			}
		}
		printk(KERN_INFO, "xnu: sd cache %u bytes @%08x (dsc full)\n",
		       cache_size, cache_pa);
	}
#else /* !J1_STAGE_CACHESLICE */
	/* Staging is OFF for the j1qemu emulator and the j1xlte phone alike,
	 * so both lanes keep the SAME mechanism: the shared cache is an
	 * ordinary file on the block rootfs, read through the stock pager
	 * (B1 plan) - not a raw RAM blob fed by dsc= + the serve table.
	 * Nothing above the ramdisk needs reserving, so park
	 * topOfKernelData right after it.  Define J1_STAGE_CACHESLICE to
	 * restore the old raw staging + dsc= bootarg. */
	top = align_up(rd_pa + rd_size, 1 << 20);
	printk(KERN_INFO, "xnu: cacheslice staging skipped, top=%x\n", top);
#endif

	ba->Revision = 1;
	ba->Version = 2;
	ba->virtBase = virt_base;
	/* BRING-UP (J1, Sep 29): use the pinned hardware values, never the
	 * generated autoconf.h - see the J1_SD_* block at the top.  A QEMU
	 * `make qemu_defconfig` run would otherwise shift physBase by
	 * 0x10800000 and move the framebuffer to the 0x50000000 placeholder. */
	ba->physBase = J1_SD_PHYS_BASE;
	ba->memSize = J1_SD_MEMSIZE;
	ba->topOfKernelData = top;

	ba->Video.v_baseAddr = J1_SD_FB_BASE;
	ba->Video.v_display = 0;
	ba->Video.v_rowBytes = J1_SD_FB_WIDTH * 4;
	ba->Video.v_width = J1_SD_FB_WIDTH;
	ba->Video.v_height = J1_SD_FB_HEIGHT;
	ba->Video.v_depth = 32;

	ba->machineType = 0;
	ba->deviceTreeP = (void *)(dt_pa - J1_SD_PHYS_BASE + virt_base);
	ba->deviceTreeLength = dtsize;

	ba->RamdiskPA = rd_pa;
	ba->RamdiskSize = rd_size;

	printk(KERN_INFO, "xnu: sd layout pa=%08x ks=%u dt=%08x(%u) "
	       "ba=%08x rd=%08x(%u) top=%08x\n",
	       load_pa, ksize, dt_pa, dtsize, ba_pa, rd_pa, rd_size, top);
	printk(KERN_INFO, "xnu: sd ba#1 vb=%08x pb=%08x ms=%08x tk=%08x\n",
	       ba->virtBase, ba->physBase, ba->memSize, ba->topOfKernelData);

	/* BRING-UP (J1): the kernel entry drifts when the build changes, so
	 * derive the jump target from the Image's own Mach-O header instead
	 * of a stale baked-in constant. */
	entry_off = sd_xnu_entry_offset(load_pa, CONFIG_XNU_ENTRY_OFFSET);
	printk(KERN_INFO, "xnu: sd entry offset %x (%s)\n", entry_off,
	       entry_off == CONFIG_XNU_ENTRY_OFFSET ? "fallback" : "parsed");
	j1_fb_stage(11);

	jump_to_xnu(load_pa + entry_off, ba_pa);

	/* Not reached. */
	return -1;
}